/** 取某个字符的笔顺路径组。非 A-Z/a-z 返回空数组。 */
export function getStrokes(char: string): string[] {
  if (!char || char.length !== 1) return [];
  if (char >= 'A' && char <= 'Z') return UPPER_STROKES[char] ?? [];
  if (char >= 'a' && char <= 'z') return LOWER_STROKES[char] ?? [];
  return [];
}
